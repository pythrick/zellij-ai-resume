#!/bin/sh
# install.sh: install zellij-ai-resume (zclaude, zcodex, zjr) for the current user.
#
# Copies the core to PREFIX/share/zellij-ai-resume and writes three small
# launchers to PREFIX/bin. Nothing else is touched: no shell rc files, no
# Zellij, Claude Code or Codex configuration. Re-run to upgrade; uninstall.sh
# removes everything it installed.
set -eu

MARK='# Generated by zellij-ai-resume install.sh'

usage() {
    cat <<'EOF'
Usage: ./install.sh [--prefix DIR] [--python PATH]

  --prefix DIR   install under DIR/bin and DIR/share (default: $HOME/.local)
  --python PATH  Python 3.8+ that runs the core (default: the macOS system
                 Python when the Command Line Tools are installed, else the
                 python3 on PATH)
EOF
}

die() {
    printf 'install.sh: %s\n' "$*" >&2
    exit 1
}

# Zellij saves a pane's command as whitespace-separated words, and these paths
# are written into the launchers between single quotes: allow plain path
# characters only.
check_path() {
    case $1 in
        /*) ;;
        *) die "$2 must be an absolute path: $1" ;;
    esac
    case $1 in
        *[!A-Za-z0-9._/+@-]*) die "$2 may contain only letters, digits and . _ / + @ -: $1" ;;
    esac
}

python_ok() {
    "$1" -I -c 'import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)' >/dev/null 2>&1
}

prefix=${HOME:?HOME is not set}/.local
python=
while [ $# -gt 0 ]; do
    case $1 in
        --prefix) [ $# -ge 2 ] || die "--prefix needs a directory"; prefix=$2; shift 2 ;;
        --prefix=*) prefix=${1#--prefix=}; shift ;;
        --python) [ $# -ge 2 ] || die "--python needs a path"; python=$2; shift 2 ;;
        --python=*) python=${1#--python=}; shift ;;
        -h | --help) usage; exit 0 ;;
        *) usage >&2; exit 2 ;;
    esac
done

here=$(cd -P -- "$(dirname -- "$0")" && pwd -P)
[ -f "$here/src/zjr.py" ] || die "run this from a checkout of zellij-ai-resume (src/zjr.py not found)"
prefix=${prefix%/}
check_path "$prefix" "--prefix"

if [ -z "$python" ]; then
    # Prefer the system's /usr/bin/python3: package managers do not move or
    # remove it. On macOS it is a stub that needs the Command Line Tools
    # (without them it opens an installer dialog), so check for them first.
    if [ -x /usr/bin/python3 ] && { [ "$(uname -s)" != Darwin ] || /usr/bin/xcode-select -p >/dev/null 2>&1; } &&
        python_ok /usr/bin/python3; then
        python=/usr/bin/python3
    else
        python=$(command -v python3 2>/dev/null) || die "python3 (3.8 or newer) not found; pass --python PATH"
        # A version manager's shim (pyenv, mise, asdf) picks a Python per
        # directory; record the interpreter it points at instead.
        case $python in
            */shims/*) python=$("$python" -I -c 'import sys; print(sys.executable)') ;;
        esac
    fi
fi
check_path "$python" "--python"
python_ok "$python" || die "$python is not a working Python 3.8 or newer"
if "$python" -I -c 'import sys; sys.exit(sys.prefix == sys.base_prefix)'; then
    echo "install.sh: warning: $python is inside a virtual environment; if it is deleted the launchers" >&2
    echo "  fall back to /usr/bin/python3 or python3 on PATH. --python can choose a lasting one." >&2
fi
case $python in
    */Cellar/* | */uv/python/cpython-* | */installs/python/[0-9]* | */.pyenv/versions/*)
        echo "install.sh: warning: $python belongs to one Python version and goes away when that" >&2
        echo "  version is removed (the launchers then fall back to another Python 3.8+)." >&2 ;;
esac
[ -x /bin/sh ] || die "/bin/sh is missing"

bindir=$prefix/bin
sharedir=$prefix/share/zellij-ai-resume
core=$sharedir/zjr.py
version=$(sed -n 's/^VERSION = "\([0-9.]*\)"$/\1/p' "$here/src/zjr.py")
[ -n "$version" ] || die "cannot read VERSION from src/zjr.py"

# Never replace a file this installer did not write.
for name in zclaude zcodex zjr; do
    target=$bindir/$name
    if [ -e "$target" ] || [ -L "$target" ]; then
        grep -qF "$MARK" "$target" 2>/dev/null ||
            die "$target exists and was not installed by zellij-ai-resume; move it away first"
    fi
done

"$python" -I -c 'import sys; compile(open(sys.argv[1]).read(), sys.argv[1], "exec")' "$here/src/zjr.py" ||
    die "src/zjr.py does not compile with $python"

umask 022
mkdir -p "$bindir" "$sharedir"

# Write through a temporary file and rename, so a pane starting during an
# upgrade never sees a half-written file.
put() {  # put SOURCE TARGET MODE
    tmp=$2.tmp.$$
    cp "$1" "$tmp"
    chmod "$3" "$tmp"
    mv -f "$tmp" "$2"
}

render() {  # render TEMPLATE TARGET TOOL
    tmp=$2.tmp.$$
    sed -e "s|@PYTHON@|$python|g" -e "s|@CORE@|$core|g" -e "s|@SELF@|$2|g" \
        -e "s|@TOOL@|$3|g" -e "s|@BINDIR@|$bindir|g" -e "s|@VERSION@|$version|g" "$1" >"$tmp"
    sh -n "$tmp" || { rm -f "$tmp"; die "generated $2 is not valid sh"; }
    chmod 755 "$tmp"
    mv -f "$tmp" "$2"
}

put "$here/src/zjr.py" "$core" 644
render "$here/src/launcher.sh.in" "$bindir/zclaude" claude
render "$here/src/launcher.sh.in" "$bindir/zcodex" codex
render "$here/src/zjr.sh.in" "$bindir/zjr" ""
printf '%s\n' "$bindir/zclaude" "$bindir/zcodex" "$bindir/zjr" "$core" >"$sharedir/manifest"

echo "Installed zellij-ai-resume $version"
echo "  launchers  $bindir/zclaude  $bindir/zcodex  $bindir/zjr"
echo "  core       $core (run by $python)"
echo "  state      \${XDG_STATE_HOME:-~/.local/state}/zellij-ai-resume (created on first use)"
echo "No shell, Zellij, Claude Code or Codex configuration was changed."
echo
"$bindir/zjr" doctor || true
