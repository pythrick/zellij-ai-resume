#!/bin/sh
# uninstall.sh: remove what install.sh installed. --purge also deletes the
# saved pane state; without it, reinstalling picks up where it left off.
#
# Zellij sessions saved while zclaude/zcodex panes were running still refer
# to the launchers: resurrecting one after uninstalling shows an error in
# those panes instead of resuming.
set -eu

MARK='# Generated by zellij-ai-resume install.sh'

die() {
    printf 'uninstall.sh: %s\n' "$*" >&2
    exit 1
}

prefix=${HOME:?HOME is not set}/.local
purge=false
while [ $# -gt 0 ]; do
    case $1 in
        --prefix) [ $# -ge 2 ] || die "--prefix needs a directory"; prefix=$2; shift 2 ;;
        --prefix=*) prefix=${1#--prefix=}; shift ;;
        --purge) purge=true; shift ;;
        -h | --help) echo "Usage: ./uninstall.sh [--prefix DIR] [--purge]"; exit 0 ;;
        *) echo "Usage: ./uninstall.sh [--prefix DIR] [--purge]" >&2; exit 2 ;;
    esac
done
prefix=${prefix%/}

for name in zclaude zcodex zjr; do
    target=$prefix/bin/$name
    if [ -f "$target" ] && grep -qF "$MARK" "$target"; then
        rm -f "$target"
        echo "removed $target"
    elif [ -e "$target" ]; then
        echo "kept $target (not installed by zellij-ai-resume)"
    fi
done

sharedir=$prefix/share/zellij-ai-resume
if [ -d "$sharedir" ]; then
    rm -f "$sharedir/zjr.py" "$sharedir/manifest"
    rmdir "$sharedir" 2>/dev/null && echo "removed $sharedir" || echo "kept $sharedir (contains other files)"
fi

# Same rule as the core: XDG_STATE_HOME counts only when it is absolute.
case ${XDG_STATE_HOME-} in
    /*) state=$XDG_STATE_HOME/zellij-ai-resume ;;
    *) state=$HOME/.local/state/zellij-ai-resume ;;
esac
if $purge; then
    if [ -d "$state" ] && [ ! -L "$state" ] && [ -O "$state" ]; then
        rm -rf -- "$state"
        echo "removed $state"
    fi
elif [ -d "$state" ]; then
    echo "kept saved pane state in $state (--purge removes it)"
fi
